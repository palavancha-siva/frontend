export const ELIGIBILITY_ACTION_TYPES = {
  CALCULATE_OFFERS_REQUEST: 'ELIGIBILITY/CALCULATE_OFFERS_REQUEST',
  CALCULATE_OFFERS_SUCCESS: 'ELIGIBILITY/CALCULATE_OFFERS_SUCCESS',
  CALCULATE_OFFERS_FAILURE: 'ELIGIBILITY/CALCULATE_OFFERS_FAILURE',
  SET_CRITERIA: 'ELIGIBILITY/SET_CRITERIA',
  RESET_OFFERS: 'ELIGIBILITY/RESET_OFFERS',
};

export const calculateOffers = (formData) => ({
  type: ELIGIBILITY_ACTION_TYPES.CALCULATE_OFFERS_REQUEST,
  payload: formData,
});

export const setCriteria = (criteria) => ({
  type: ELIGIBILITY_ACTION_TYPES.SET_CRITERIA,
  payload: criteria,
});

export const resetOffers = () => ({
  type: ELIGIBILITY_ACTION_TYPES.RESET_OFFERS,
});
