export const PORTAL_ACTION_TYPES = {
  FETCH_APPLICATIONS_REQUEST: 'PORTAL/FETCH_APPLICATIONS_REQUEST',
  FETCH_APPLICATIONS_SUCCESS: 'PORTAL/FETCH_APPLICATIONS_SUCCESS',
  FETCH_APPLICATIONS_FAILURE: 'PORTAL/FETCH_APPLICATIONS_FAILURE',

  FETCH_CIBIL_REQUEST: 'PORTAL/FETCH_CIBIL_REQUEST',
  FETCH_CIBIL_SUCCESS: 'PORTAL/FETCH_CIBIL_SUCCESS',
  FETCH_CIBIL_FAILURE: 'PORTAL/FETCH_CIBIL_FAILURE',

  UPDATE_PROFILE_REQUEST: 'PORTAL/UPDATE_PROFILE_REQUEST',
  UPDATE_PROFILE_SUCCESS: 'PORTAL/UPDATE_PROFILE_SUCCESS',
  UPDATE_PROFILE_FAILURE: 'PORTAL/UPDATE_PROFILE_FAILURE',
};

export const fetchApplications = () => ({
  type: PORTAL_ACTION_TYPES.FETCH_APPLICATIONS_REQUEST,
});

export const fetchCibil = (pan) => ({
  type: PORTAL_ACTION_TYPES.FETCH_CIBIL_REQUEST,
  payload: { pan },
});

export const updateProfile = (profileData) => ({
  type: PORTAL_ACTION_TYPES.UPDATE_PROFILE_REQUEST,
  payload: profileData,
});
